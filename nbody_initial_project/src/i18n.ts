// 觸發時 dx 通常只比 skin 多一點點：逐步增加小數位數，直到兩者顯示得出差異（最多 6 位）
const fmtTrigger = (e: RebuildEvent): [string, string] => {
  for (let digits = 3; digits < 6; digits += 1) {
    const dx = e.displacement.toFixed(digits); const skin = e.skinAtTrigger.toFixed(digits);
    if (dx !== skin) return [dx, skin];
  }
  return [e.displacement.toFixed(6), e.skinAtTrigger.toFixed(6)];
};

