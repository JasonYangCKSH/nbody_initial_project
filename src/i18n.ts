const STORAGE_KEY = 'collision-lab-lang';

export const loadLang = (): Lang => {
  try { return localStorage.getItem(STORAGE_KEY) === 'zh' ? 'zh' : 'en'; } catch { return 'en'; }
};

export const saveLang = (lang: Lang): void => {
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* 無痕視窗等情況下忽略 */ }
};
